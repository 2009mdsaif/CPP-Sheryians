#include<iostream>
using namespace std;
int main (){
// increment and decrement operators are used to increase or decrease the value of a variable by 1:
int a=2, b=3;
    cout<<a++<<endl; //post increment
    cout<<a<<endl; //value of a after post increment
    cout<<++a<<endl; //pre increment
    cout<<a<<endl; //value of a after pre increment
    cout<<a--<<endl; //post decrement
    cout<<a<<endl; //value of a after post decrement
    cout<<--a<<endl; //pre decrement
    cout<<a<<endl; //value of a after pre decrement
    cout<<b++<<endl; //post increment
    cout<<b<<endl; //value of b after post increment
    cout<<++b<<endl; //pre increment
    cout<<b<<endl; //value of b after pre increment
    cout<<b--<<endl; //post decrement
    cout<<b<<endl; //value of b after post decrement    
    cout<<--b<<endl; //pre decrement
    cout<<b<<endl; //value of b after pre decrement

}