#include<iostream>
using namespace std;
int main (){
    int a=5,b=10;
    cout<<(a>b)<<endl; //greater than
    cout<<(a<b)<<endl; //less than
    cout<<(a==b)<<endl; //equal to
    cout<<(a!=b)<<endl; //not equal to
    cout<<(a>=b)<<endl; //greater than or equal to
    cout<<(a<=b)<<endl; //less than or equal to
}